    }

    // ── Cache MISS + 2xx → calls next, caches response ───────────────────────────

    [Fact]
    public async Task OnActionExecutionAsync_CacheMiss_2xxResult_CachesResponse()
    {
        var filter = CreateFilter();
        var key = Guid.NewGuid().ToString();

        var cache = Substitute.For<IDistributedCache>();
        // GetAsync returns null (cache miss)
        cache.GetAsync($"idem:{key}", Arg.Any<CancellationToken>())
             .Returns((byte[]?)null);

        var services = new ServiceCollection();
        services.AddSingleton<IDistributedCache>(cache);
        var (ctx, _) = BuildContext(idempotencyKey: key, services: services.BuildServiceProvider());

        var next = NextDelegateWithResult(new ObjectResult("created") { StatusCode = 201 });

        await filter.OnActionExecutionAsync(ctx, next);

        // Verify SetAsync was called (response was cached)
        await cache.Received(1).SetAsync(
            $"idem:{key}",
            Arg.Any<byte[]>(),
            Arg.Any<DistributedCacheEntryOptions>(),
            Arg.Any<CancellationToken>());
    }

