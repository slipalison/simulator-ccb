    // ── Cache HIT → returns stored response, does NOT call next ──────────────────

    [Fact]
    public async Task OnActionExecutionAsync_CacheHit_SetsResultFromCache_DoesNotCallNext()
    {
        var filter = CreateFilter();
        var key = Guid.NewGuid().ToString();

        // Serialize a stored response the same way the production code does
        var storedValue = new { value = "cached-body", status = 201 };
        var storedJson = System.Text.Json.JsonSerializer.Serialize(
            new { StatusCode = 201, Value = (object)"cached-body" });

        var cache = Substitute.For<IDistributedCache>();
        cache.GetAsync($"idem:{key}", Arg.Any<CancellationToken>())
             .Returns(System.Text.Encoding.UTF8.GetBytes(storedJson));

        var services = new ServiceCollection();
        services.AddSingleton<IDistributedCache>(cache);
        var (ctx, _) = BuildContext(idempotencyKey: key, services: services.BuildServiceProvider());

        var nextCalled = false;
        ActionExecutionDelegate next = () =>
        {
            nextCalled = true;
            return Task.FromResult(NextDelegate().Invoke().Result);
        };

        await filter.OnActionExecutionAsync(ctx, next);

        nextCalled.ShouldBeFalse("next must NOT be called on cache hit");
        ctx.Result.ShouldNotBeNull("result must be set from cache");
        var objectResult = ctx.Result.ShouldBeOfType<ObjectResult>();
        objectResult.StatusCode.ShouldBe(201);
    }

    [Fact]
    public async Task OnActionExecutionAsync_CacheHit_ReturnsStoredStatusCode()
    {
        var filter = CreateFilter();
