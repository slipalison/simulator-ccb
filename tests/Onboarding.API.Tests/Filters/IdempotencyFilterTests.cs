        // Production code deserializes IdempotentResponse(StatusCode, Value)
        var storedJson = System.Text.Json.JsonSerializer.Serialize(
            new { StatusCode = 201, Value = (object)new { id = "abc123" } });

        var cache = Substitute.For<IDistributedCache>();
