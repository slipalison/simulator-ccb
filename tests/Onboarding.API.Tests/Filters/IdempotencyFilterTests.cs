using System.Reflection;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Abstractions;
using Microsoft.AspNetCore.Mvc.Filters;
using Microsoft.AspNetCore.Routing;
using Microsoft.Extensions.Caching.Distributed;
using Microsoft.Extensions.DependencyInjection;
using NSubstitute;
using Shouldly;

namespace Onboarding.API.Tests.Filters;

/// <summary>
/// Unit tests for the internal IdempotentAttribute action filter (REG-08).
/// The type is internal to Onboarding.API so we access it via reflection + IAsyncActionFilter cast.
///
/// Scenarios:
/// - No Idempotency-Key header → passthrough (next called)
/// - Non-GUID Idempotency-Key header → passthrough (REG-08 silently ignores non-GUIDs)
/// - Cache hit (valid GUID key) → returns stored response without calling next
/// - Cache miss (valid GUID key) → calls next, caches 2xx response
/// - Cache miss + 4xx response → calls next, does NOT cache
/// - Cache miss + 5xx response → calls next, does NOT cache
/// </summary>
public class IdempotencyFilterTests
{
    // ── Filter instantiation via reflection (internal type) ───────────────────────

    // Program is generated by top-level statements in the global namespace.
    // We resolve the internal type via the API assembly at runtime.
    private static readonly Type IdempotentAttributeType =
        typeof(Program).Assembly
            .GetType("Onboarding.API.Filters.IdempotentAttribute", throwOnError: true)!;

    private static IAsyncActionFilter CreateFilter()
    {
        return (IAsyncActionFilter)Activator.CreateInstance(IdempotentAttributeType)!;
    }

    // ── ActionExecutingContext helpers ────────────────────────────────────────────

    private static (ActionExecutingContext, IDistributedCache) BuildContext(
        string? idempotencyKey = null,
        IServiceProvider? services = null)
    {
        var cache = Substitute.For<IDistributedCache>();

        if (services is null)
        {
            var serviceCollection = new ServiceCollection();
            serviceCollection.AddSingleton<IDistributedCache>(cache);
            services = serviceCollection.BuildServiceProvider();
        }

        var httpContext = new DefaultHttpContext { RequestServices = services };

        if (idempotencyKey is not null)
            httpContext.Request.Headers["Idempotency-Key"] = idempotencyKey;

        var actionContext = new ActionContext(
            httpContext,
            new RouteData(),
            new ActionDescriptor());

        var context = new ActionExecutingContext(
            actionContext,
            filters: new List<IFilterMetadata>(),
            actionArguments: new Dictionary<string, object?>(),
            controller: new object());

        return (context, cache);
    }

    private static ActionExecutionDelegate NextDelegate(ActionExecutedContext? executedCtx = null)
    {
        return () => Task.FromResult(executedCtx ?? new ActionExecutedContext(
            new ActionContext(
                new DefaultHttpContext(),
                new RouteData(),
                new ActionDescriptor()),
            new List<IFilterMetadata>(),
            controller: new object()));
    }

    private static ActionExecutionDelegate NextDelegateWithResult(IActionResult result)
    {
        var executed = new ActionExecutedContext(
            new ActionContext(
                new DefaultHttpContext(),
                new RouteData(),
                new ActionDescriptor()),
            new List<IFilterMetadata>(),
            controller: new object())
        {
            Result = result
        };

        return () => Task.FromResult(executed);
    }

    // ── No Idempotency-Key header → passthrough ───────────────────────────────────

    [Fact]
    public async Task OnActionExecutionAsync_NoIdempotencyKeyHeader_CallsNext()
    {
        var filter = CreateFilter();
        var (ctx, cache) = BuildContext(idempotencyKey: null);

        var nextCalled = false;
        ActionExecutionDelegate next = () =>
        {
            nextCalled = true;
            return Task.FromResult(NextDelegateWithResult(new OkResult()).Invoke().Result);
        };

        await filter.OnActionExecutionAsync(ctx, next);

        nextCalled.ShouldBeTrue("next must be called when no Idempotency-Key header is present");
        ctx.Result.ShouldBeNull("no short-circuit when header is absent");
    }

    [Fact]
    public async Task OnActionExecutionAsync_NoIdempotencyKeyHeader_DoesNotAccessCache()
    {
        var filter = CreateFilter();
        var (ctx, cache) = BuildContext(idempotencyKey: null);

        await filter.OnActionExecutionAsync(ctx, NextDelegate());

        // Cache must not be consulted when header is absent
        await cache.DidNotReceiveWithAnyArgs().GetAsync(default!, default);
    }

    // ── Non-GUID Idempotency-Key → passthrough (REG-08 silently ignores) ─────────

